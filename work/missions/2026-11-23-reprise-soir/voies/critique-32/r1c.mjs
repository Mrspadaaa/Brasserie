import { ouvrir, sleep, photo, log, boutons, glisser, ou } from './outil.mjs';
import { etat } from './lire.mjs';
import { outils, court, periode } from './commun.mjs';
const { page, cdp, lacher } = await ouvrir();
page.on('framenavigated', (f) => { if (f === page.mainFrame()) log('NAVIGATION', f.url()); });
const { pas, tap } = outils(page, cdp);
const poi = async (n) => { const r = await ou(page, 'Poignée de ' + n, 'button,[role=slider]'); return r; };
const per = async () => (await etat(page)).periode;
log('départ', court(await etat(page)), await per());
let p = await poi('début'); log('poignée début', p?.aria);
await pas('R1-03-debut-gauche', () => glisser(cdp, p.x, p.y, p.x - 40, p.y, { tenir: 150 }), false);
log('période', await per(), (await poi('début'))?.aria);
p = await poi('fin'); log('poignée fin', p?.aria);
await pas('R1-04-fin-gauche100', () => glisser(cdp, p.x, p.y, p.x - 100, p.y, { tenir: 150 }), false);
log('période', await per());
p = await poi('fin');
await pas('R1-05-fin-gauche60', () => glisser(cdp, p.x, p.y, p.x - 60, p.y, { tenir: 150 }), false);
p = await poi('fin');
await pas('R1-06-fin-droite120', () => glisser(cdp, p.x, p.y, p.x + 120, p.y, { tenir: 150 }), false);
log('période', await per());
// période 4 ans remise, puis › et ‹
await periode(page, cdp, tap, '01.01.2024', '31.12.2027');
await pas('R1-07-4ans', null);
await pas('R1-08-suivante', () => tap('Période suivante'), false); log('période', await per());
await pas('R1-09-precedente', () => tap('Période précédente'), false); log('période', await per());
await pas('R1-10-precedente2', () => tap('Période précédente'), false); log('période', await per());
await periode(page, cdp, tap, 'Tout');
await pas('R1-11-tout', null, false); log('période', await per());
lacher();
